const uint8_t *font_glyph_rows(char ch)
{
    unsigned char uc = (unsigned char)ch;

    if (uc < MDE_FONT_FIRST_CP || uc > MDE_FONT_LAST_CP)
        return mde_font_bitmap['?' - MDE_FONT_FIRST_CP];

    return mde_font_bitmap[uc - MDE_FONT_FIRST_CP];
}

void font_metrics(mde_font_metrics_t *out)
{
    if (!out)
        return;
    out->cell_w = MDE_FONT_CELL_W;
    out->cell_h = MDE_FONT_CELL_H;
    out->advance = MDE_FONT_ADVANCE;
    out->first_cp = MDE_FONT_FIRST_CP;
    out->last_cp = MDE_FONT_LAST_CP;
}

int32_t font_string_advance(const char *text)
{
    int32_t n = 0;

    if (!text)
        return 0;
    while (text[n] != '\0')
        n++;
    return n * MDE_FONT_ADVANCE;
}

void font_draw_glyph(draw_surface_t *dst, int32_t x, int32_t y, char ch,
                     uint32_t fg, uint32_t bg, int transparent_bg)
{
    const uint8_t *rows;
    int32_t row;
    int32_t col;

    if (!dst)
        return;

    fg = draw_color_from_theme(fg);
    bg = draw_color_from_theme(bg);
    rows = font_glyph_rows(ch);

    for (row = 0; row < MDE_FONT_CELL_H; row++) {
        uint8_t bits = rows[row];
        for (col = 0; col < MDE_FONT_CELL_W; col++) {
            if (bits & (0x80u >> (uint32_t)col))
                draw_pixel(dst, x + col, y + row, fg);
            else if (!transparent_bg)
                draw_pixel(dst, x + col, y + row, bg);
        }
    }
}

void font_draw_string(draw_surface_t *dst, int32_t x, int32_t y, const char *text,
                      uint32_t fg, uint32_t bg, int transparent_bg)
{
    int32_t pen_x = x;

    if (!dst || !text)
        return;

    while (*text) {
        font_draw_glyph(dst, pen_x, y, *text, fg, bg, transparent_bg);
        pen_x += MDE_FONT_ADVANCE;
        text++;
    }
}
